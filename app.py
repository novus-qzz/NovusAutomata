def add(a: int, b: int) -> int:
    """Add two integers together.

    Args:
        a: First integer.
        b: Second integer.

    Returns:
        Sum of a and b.
    """
    return a + b


def multiply(a: int, b: int) -> int:
    """Multiply two integers.

    Args:
        a: First integer.
        b: Second integer.

    Returns:
        Product of a and b.
    """
    return a * b


def greet(name: str) -> str:
    """Greet a person by name.

    Args:
        name: Person's name.

    Returns:
        Greeting string.
    """
    return f"Hello, {name}!"
